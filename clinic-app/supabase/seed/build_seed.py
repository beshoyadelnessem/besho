"""Generates migrations/0006_seed_acl.sql and the web demo copy from exercises_acl.json.

    python3 supabase/seed/build_seed.py
"""
import json
from pathlib import Path

here = Path(__file__).resolve().parent
items = json.loads((here / "exercises_acl.json").read_text(encoding="utf-8"))

langs = ("en", "ar", "de")
for e in items:
    for lang in langs:
        c = e["content"][lang]
        assert c["name"] and c["steps"] and c["caution"], (e["slug"], lang)

def q(s):
    return "'" + s.replace("'", "''") + "'"

rows = []
for e in items:
    rows.append("(" + ", ".join([
        q(e["slug"]), str(e["phase"]), str(e["sort"]), str(e["default_sets"]), str(e["default_reps"]),
        str(e["default_hold_sec"]), q(json.dumps(e["content"], ensure_ascii=False)) + "::jsonb",
    ]) + ")")

sql = (
    "-- Generated by supabase/seed/build_seed.py from exercises_acl.json. Do not edit by hand.\n"
    "-- ACL home-exercise library (shared by all clinics). Doses are defaults; the therapist sets each patient's own.\n"
    "insert into public.exercises (slug, phase, sort, default_sets, default_reps, default_hold_sec, content) values\n"
    + ",\n".join(rows)
    + "\non conflict (slug) do update set phase = excluded.phase, sort = excluded.sort, default_sets = excluded.default_sets,\n"
    "  default_reps = excluded.default_reps, default_hold_sec = excluded.default_hold_sec, content = excluded.content;\n"
)
(here.parent / "migrations" / "0006_seed_acl.sql").write_text(sql, encoding="utf-8")

demo = [dict(e, clinic_id=None, condition="acl") for e in items]
(here.parent.parent / "web" / "src" / "api" / "demo-exercises.json").write_text(
    json.dumps(demo, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
print(f"{len(items)} exercises written")
